#ifndef CANGJIE_AST_NODES_REFERENCE_H
#define CANGJIE_AST_NODES_REFERENCE_H

#include "cangjie/AST/Identifier.h"
#include "cangjie/AST/Nodes/ASTKind.h"

namespace Cangjie {
class PartialInstantiation;
}

namespace Cangjie::AST {
struct Decl;
struct Reference {
    /**< Reference's name. (When it's text is raw identifier the raw mark "``" will be removed.
     * e.g., name of "`type_1`" is "type_1".) Generated by Parser. */
    SrcIdentifier identifier;

    Reference() = default;
    explicit Reference(const SrcIdentifier& id) : identifier{id}
    {
    }
    explicit Reference(SrcIdentifier&& id) : identifier{std::move(id)}
    {
    }

    explicit Reference(const std::string& name) : identifier{name, INVALID_POSITION, INVALID_POSITION, false}
    {
    }

    Ptr<Decl> GetTarget() const noexcept;
    void SetTarget(Ptr<Decl> newTarget) noexcept;
    std::vector<Ptr<Decl>> GetTargets() const;
    void SetTargets(std::vector<Ptr<Decl>> newTargets);
    void AddTarget(Ptr<Decl> decl);

private:
    // Friends only: ASTCloner / PartialInstantiation record addresses of these Ptr<Decl> fields when building the
    // source↔clone rearrange map (see TargetAddrMapInsert). All other code uses GetTarget / SetTarget / GetTargets.
    friend class ASTCloner;
    friend class ::Cangjie::PartialInstantiation;
    Ptr<Decl> target{nullptr};      /**< Target of the Reference. */
    std::vector<Ptr<Decl>> targets; /**< Overloaded Functions or super class/interfaces. */
};
} // namespace Cangjie::AST

#endif // CANGJIE_AST_NODES_REFERENCE_H
