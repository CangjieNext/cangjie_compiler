"""Generate one application-owned context provider before compiling consumers.

This generates source, not a preinstalled SDK runtime. Conversion code belongs
to compiler-generated foreign wrappers. A final application must link all of
its consumers against the same dynamic provider; generation alone proves
neither that link contract nor context isolation at runtime.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re


PACKAGE = "cj_arkts_context_v1"
ABI = 1
TEMPLATE = """// Copyright (c) Huawei Technologies Co., Ltd. 2026. All rights reserved.
// Licensed under Apache-2.0 with Runtime Library Exception.
// Generated by utils/arkts/generate_context.py. Do not edit.
package cj_arkts_context_v1

import ohos.ark_interop.JSContext

let CURRENT_CONTEXT = ThreadLocal<JSContext>()

public func __cj_arkts_enter(ctx: JSContext): ?JSContext {
    ctx.getNapiEnv()
    let previous = CURRENT_CONTEXT.get()
    CURRENT_CONTEXT.set(Some(ctx))
    return previous
}

public func __cj_arkts_current(): JSContext {
    let ctx = CURRENT_CONTEXT.get() ?? throw Exception("ARKTS_NO_CALLING_CONTEXT")
    ctx.getNapiEnv()
    return ctx
}

public func __cj_arkts_restore(previous: ?JSContext): Unit {
    CURRENT_CONTEXT.set(previous)
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app-id", required=True)
    parser.add_argument("--target", required=True,
                        choices=("x86_64-linux-ohos", "aarch64-linux-ohos"))
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,127}", args.app_id):
        parser.error("app-id must be a 1..128 character application identifier")
    # Require a fresh directory: never overwrite another application's provider.
    args.output_dir.mkdir(parents=True, exist_ok=False)
    source = TEMPLATE.encode("utf-8")
    (args.output_dir / "context.cj").write_bytes(source)
    manifest = {
        "schema_version": 1,
        "application_id": args.app_id,
        "target": args.target,
        "context_abi": ABI,
        "logical_package": PACKAGE,
        "source": "context.cj",
        "source_sha256": hashlib.sha256(source).hexdigest(),
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "provider_filename": "libcj_arkts_context_v1.so",
        "consumer_link_mode": "one_dynamic_provider_per_application",
        "build_status": "SourceGenerated",
        "runtime_verified": False,
    }
    (args.output_dir / "context-manifest.json").write_bytes(
        (json.dumps(manifest, indent=2) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
